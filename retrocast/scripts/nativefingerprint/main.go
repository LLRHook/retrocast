// nativefingerprint makes a linked Rust archive part of Go's build-cache inputs.
package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"io"
	"os"
	"path/filepath"
)

func writeFingerprint(archive, output string) error {
	input, err := os.Open(archive)
	if err != nil {
		return err
	}
	defer input.Close()
	hash := sha256.New()
	if _, err := io.Copy(hash, input); err != nil {
		return err
	}
	content := []byte(fmt.Sprintf("// Code generated by scripts/nativefingerprint; DO NOT EDIT.\npackage permissions\n\nconst nativeArchiveFingerprint = %q\n", fmt.Sprintf("%x", hash.Sum(nil))))
	previous, err := os.ReadFile(output)
	if err == nil && bytes.Equal(previous, content) {
		return nil
	}
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(output), ".native-fingerprint-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(content); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), output)
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: nativefingerprint ARCHIVE GENERATED_GO_FILE")
		os.Exit(1)
	}
	if err := writeFingerprint(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintf(os.Stderr, "native fingerprint: %v\n", err)
		os.Exit(1)
	}
}
